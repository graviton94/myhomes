// Generates lib/design/tokens.g.dart from ../design/tokens.json.
//
//   dart run tool/generate.dart          write the file
//   dart run tool/generate.dart --check  fail if the file is out of date (CI)
import 'dart:convert';
import 'dart:io';

const _out = 'lib/design/tokens.g.dart';

void main(List<String> args) {
  final check = args.contains('--check');
  final json = jsonDecode(File('../design/tokens.json').readAsStringSync()) as Map<String, dynamic>;
  final code = _render(json);
  final file = File(_out);
  if (check) {
    if (!file.existsSync() || file.readAsStringSync() != code) {
      stderr.writeln('$_out is out of date. Run: dart run tool/generate.dart');
      exit(1);
    }
    stdout.writeln('$_out is up to date.');
    return;
  }
  file.createSync(recursive: true);
  file.writeAsStringSync(code);
  stdout.writeln('Wrote $_out');
}

String _hex(String v) {
  final h = v.replaceFirst('#', '').toUpperCase();
  return h.length == 6 ? '0xFF$h' : '0x$h';
}

String _render(Map<String, dynamic> t) {
  final colors = t['color'] as Map<String, dynamic>;
  final light = colors['light'] as Map<String, dynamic>;
  final dark = colors['dark'] as Map<String, dynamic>;
  if (light.keys.toSet().difference(dark.keys.toSet()).isNotEmpty ||
      dark.keys.toSet().difference(light.keys.toSet()).isNotEmpty) {
    stderr.writeln('Light and dark colour names differ.');
    exit(1);
  }
  final names = light.keys.toList();
  final b = StringBuffer()
    ..writeln('// GENERATED by tool/generate.dart from design/tokens.json. Do not edit.')
    ..writeln('// ignore_for_file: lines_longer_than_80_chars')
    ..writeln()
    ..writeln("import 'package:flutter/painting.dart';")
    ..writeln()
    ..writeln('/// Colour tokens. Light and dark share names; only values differ.')
    ..writeln('class AppColors {')
    ..writeln('  const AppColors({');
  for (final n in names) {
    b.writeln('    required this.$n,');
  }
  b.writeln('  });');
  b.writeln();
  for (final n in names) {
    b.writeln('  final Color $n;');
  }
  for (final mode in ['light', 'dark']) {
    final values = colors[mode] as Map<String, dynamic>;
    b
      ..writeln()
      ..writeln('  static const AppColors $mode = AppColors(');
    for (final n in names) {
      b.writeln('    $n: Color(${_hex(values[n] as String)}),');
    }
    b.writeln('  );');
  }
  b
    ..writeln('}')
    ..writeln();

  final fonts = t['font'] as Map<String, dynamic>;
  b.writeln('/// Font families with their fallback chains (Korean glyphs fall back to Jua / Noto Sans KR).');
  b.writeln('abstract final class AppFonts {');
  fonts.forEach((k, v) {
    final f = v as Map<String, dynamic>;
    final fb = (f['fallback'] as List).map((e) => "'$e'").join(', ');
    b.writeln("  static const String $k = '${f['family']}';");
    b.writeln('  static const List<String> ${k}Fallback = [$fb];');
  });
  b
    ..writeln('}')
    ..writeln();

  final type = t['type'] as Map<String, dynamic>;
  b.writeln('/// Type scale.');
  b.writeln('abstract final class AppType {');
  type.forEach((k, v) {
    final s = v as Map<String, dynamic>;
    final font = s['font'] as String;
    b.writeln('  static const TextStyle $k = TextStyle(');
    b.writeln('    fontFamily: AppFonts.$font,');
    b.writeln('    fontFamilyFallback: AppFonts.${font}Fallback,');
    b.writeln('    fontSize: ${s['size']},');
    b.writeln('    fontWeight: FontWeight.w${s['weight']},');
    b.writeln('    height: ${s['height']},');
    b.writeln('  );');
  });
  b
    ..writeln('}')
    ..writeln();

  void numbers(String cls, String key, String doc, String type) {
    final m = t[key] as Map<String, dynamic>;
    b.writeln('/// $doc');
    b.writeln('abstract final class $cls {');
    m.forEach((k, v) => b.writeln('  static const $type $k = $v${type == 'double' && v is int ? '.0' : ''};'));
    b
      ..writeln('}')
      ..writeln();
  }

  numbers('AppRadius', 'radius', 'Corner radii in logical pixels.', 'double');
  numbers('AppSpace', 'space', 'Spacing scale in logical pixels.', 'double');
  numbers('AppSize', 'size', 'Fixed sizes. touch = minimum touch target (48dp).', 'double');
  numbers('AppMotion', 'motion', 'Durations in milliseconds.', 'int');
  return '${b.toString().trimRight()}\n';
}
