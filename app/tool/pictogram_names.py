"""Names of the ordered pictograms (docs/asset-brief/icon-orders.json, sheet 1
below), written to core's pictograms.g.dart so a name finds its picture.

    python3 tool/pictogram_names.py
"""
import json, os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ORDERS = os.path.join(ROOT, '..', 'docs', 'asset-brief', 'icon-orders.json')
OUT = os.path.join(ROOT, 'packages', 'core', 'lib', 'src', 'pictograms.g.dart')

# Sheet 1 (rooms and furniture), in the order it was drawn.
SHEET1 = ('거실 안방 아이방 서재 주방 욕실 화장실 다용도실 베란다 현관 드레스룸 창고 다락 차고 '
          'TV장 거실장 신발장 책장 옷장 서랍장 화장대 협탁 장식장 책상 냉장고 김치냉장고 냉동고 세탁기 '
          '건조기 식기세척기 전자레인지 오븐 싱크대 찬장 팬트리 욕실장 세면대 수건장 벽선반 행거 리빙박스 '
          '라탄바구니 수납서랍 여행가방 공구함 구급상자 에어컨 화분선반 벽걸이후크').split()
assert len(SHEET1) == 49


def main():
    sheets = [{'title': '방 · 가구', 'names': SHEET1}] + json.load(open(ORDERS))
    lines = [
        '// GENERATED by tool/pictogram_names.py from docs/asset-brief/icon-orders.json. Do not edit.',
        '',
        '/// The ordered pictograms by key ("p0101": sheet 1, top left) and their',
        '/// names as ordered. The app draws them with HfPictos.',
        'const Map<String, String> pictogramNames = {',
    ]
    for s, sheet in enumerate(sheets, start=1):
        for c, name in enumerate(sheet['names'], start=1):
            lines.append(f"  'p{s:02d}{c:02d}': '{name}',")
    lines += ['};', '', f'/// Sheets in order (1 to {len(sheets)}): the picker shows one group each.', f'const int pictogramSheetCount = {len(sheets)};', '']
    open(OUT, 'w').write('\n'.join(lines))
    print('sheets', len(sheets), 'names', sum(len(s['names']) for s in sheets))


if __name__ == '__main__':
    main()
