"""Bakes design/icons/*.svg (24x24, filled) into assets/fonts/HfIcons.ttf and
writes lib/widgets/hf_icons.g.dart so the app can draw them like Material icons.

    python3 tool/build_icons.py          # build
    python3 tool/build_icons.py --check  # fail if the outputs are stale
"""
import glob
import hashlib
import io
import os
import sys

from fontTools.fontBuilder import FontBuilder
from fontTools.pens.cu2quPen import Cu2QuPen
from fontTools.pens.transformPen import TransformPen
from fontTools.pens.ttGlyphPen import TTGlyphPen
from fontTools.svgLib.path import parse_path
import xml.etree.ElementTree as ET

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, '..', 'design', 'icons')
FONT = os.path.join(ROOT, 'assets', 'fonts', 'HfIcons.ttf')
DART = os.path.join(ROOT, 'lib', 'widgets', 'hf_icons.g.dart')
UPM = 1200  # 24 grid units x 50
FIRST = 0xE000


def glyph_for(svg_path):
    d = ' '.join(p.get('d') for p in ET.parse(svg_path).getroot().iter('{http://www.w3.org/2000/svg}path'))
    pen = TTGlyphPen(None)
    # SVG y grows down; font y grows up. Fill the whole em like Material icons.
    parse_path(d, TransformPen(Cu2QuPen(pen, max_err=1.0, reverse_direction=True), (50, 0, 0, -50, 0, UPM)))
    return pen.glyph()


def build():
    names = sorted(os.path.basename(p)[:-4] for p in glob.glob(os.path.join(SRC, '*.svg')))
    glyphs = {'.notdef': TTGlyphPen(None).glyph()}
    cmap = {}
    for i, n in enumerate(names):
        glyphs[n] = glyph_for(os.path.join(SRC, n + '.svg'))
        cmap[FIRST + i] = n
    fb = FontBuilder(UPM, isTTF=True)
    fb.setupGlyphOrder(['.notdef', *names])
    fb.setupCharacterMap(cmap)
    fb.setupGlyf(glyphs)
    fb.setupHorizontalMetrics({g: (UPM, 0) for g in ['.notdef', *names]})
    fb.setupHorizontalHeader(ascent=UPM, descent=0)
    fb.setupNameTable({'familyName': 'HfIcons', 'styleName': 'Regular'})
    fb.setupOS2(sTypoAscender=UPM, sTypoDescender=0, usWinAscent=UPM, usWinDescent=0)
    fb.setupPost()
    buf = io.BytesIO()
    fb.save(buf)
    lines = [
        '// GENERATED by tool/build_icons.py from design/icons. Do not edit.',
        "import 'package:flutter/widgets.dart';",
        '',
        '/// Clothes and pets drawn to match Material icons (Material has none).',
        'abstract final class HfIcons {',
    ]
    for i, n in enumerate(names):
        lines.append(f"  static const IconData {n} = IconData(0x{FIRST + i:X}, fontFamily: 'HfIcons');")
    lines += ['}', '']
    return buf.getvalue(), '\n'.join(lines)


def main():
    font, dart = build()
    if '--check' in sys.argv:
        # Font bytes can differ by timestamp, so compare the glyph outlines' hash via the Dart file and names.
        ok = os.path.exists(FONT) and os.path.exists(DART) and open(DART).read() == dart
        if not ok:
            print('HfIcons is out of date. Run: python3 tool/build_icons.py')
            sys.exit(1)
        print('HfIcons is up to date.')
        return
    open(FONT, 'wb').write(font)
    open(DART, 'w').write(dart)
    print(f'Wrote {dart.count("static const")} icons, {len(font)} bytes, sha1 {hashlib.sha1(font).hexdigest()[:8]}')


if __name__ == '__main__':
    main()
