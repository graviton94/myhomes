"""Bakes design/icons/*.svg (24x24, filled) into assets/fonts/HfIcons.ttf and
writes lib/widgets/hf_icons.g.dart so the app can draw them like Material icons.

    python3 tool/build_icons.py          # build
    python3 tool/build_icons.py --check  # fail if the outputs are stale
"""
import glob
import hashlib
import io
import os
import sys

from fontTools.fontBuilder import FontBuilder
from fontTools.pens.boundsPen import BoundsPen
from fontTools.pens.cu2quPen import Cu2QuPen
from fontTools.pens.recordingPen import RecordingPen
from fontTools.pens.transformPen import TransformPen
from fontTools.pens.ttGlyphPen import TTGlyphPen
from fontTools.svgLib.path import parse_path
import xml.etree.ElementTree as ET

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, '..', 'design', 'icons')
FONT = os.path.join(ROOT, 'assets', 'fonts', 'HfIcons.ttf')
DART = os.path.join(ROOT, 'lib', 'widgets', 'hf_icons.g.dart')
UPM = 1200  # 24 grid units x 50
FIRST = 0xE000


def glyph_for(svg_path):
    root = ET.parse(svg_path).getroot()
    d = ' '.join(p.get('d') for p in root.iter('{http://www.w3.org/2000/svg}path'))
    # Borrowed CC0 sets use other grids (Pinhead is 15x15); scale to 24.
    k = 45 * 24 / float((root.get('viewBox') or '0 0 24 24').split()[2])
    # SVG y grows down; font y grows up. 24 grid units -> UPM at 90% so the
    # optical size matches Material (about 20x16 for wide shapes).
    shape = RecordingPen()
    parse_path(d, TransformPen(shape, (k, 0, 0, -k, 0, 0)))
    bounds = BoundsPen(None)
    shape.replay(bounds)
    x0, y0, x1, y1 = bounds.bounds
    # Centre the outline in the em, as Material icons are.
    dx, dy = UPM / 2 - (x0 + x1) / 2, UPM / 2 - (y0 + y1) / 2
    pen = TTGlyphPen(None)
    shape.replay(TransformPen(Cu2QuPen(pen, max_err=1.0, reverse_direction=True), (1, 0, 0, 1, dx, dy)))
    return pen.glyph()


def build(src=SRC, family='HfIcons'):
    names = sorted(os.path.basename(p)[:-4] for p in glob.glob(os.path.join(src, '*.svg')))
    glyphs = {'.notdef': TTGlyphPen(None).glyph()}
    cmap = {}
    for i, n in enumerate(names):
        glyphs[n] = glyph_for(os.path.join(src, n + '.svg'))
        cmap[FIRST + i] = n
    fb = FontBuilder(UPM, isTTF=True)
    fb.setupGlyphOrder(['.notdef', *names])
    fb.setupCharacterMap(cmap)
    fb.setupGlyf(glyphs)
    # The left side bearing must equal each outline's xMin; renderers shift the
    # outline to match it, so 0 here pushed every icon to the left.
    glyf = fb.font['glyf']
    metrics = {'.notdef': (UPM, 0)}
    for n in names:
        glyf[n].recalcBounds(glyf)
        metrics[n] = (UPM, glyf[n].xMin)
    fb.setupHorizontalMetrics(metrics)
    fb.setupHorizontalHeader(ascent=UPM, descent=0)
    fb.setupNameTable({'familyName': family, 'styleName': 'Regular'})
    fb.setupOS2(sTypoAscender=UPM, sTypoDescender=0, usWinAscent=UPM, usWinDescent=0)
    fb.setupPost()
    # Fixed timestamps so the same sources always give the same bytes.
    fb.font['head'].created = fb.font['head'].modified = 0
    buf = io.BytesIO()
    fb.save(buf)
    if family == 'HfPictos':
        lines = [
            '// GENERATED by tool/build_icons.py from design/icons/sheets. Do not edit.',
            "import 'package:flutter/widgets.dart';",
            '',
            '/// The ordered pictogram sheets (docs/asset-brief/sheets), one key per',
            '/// cell: p + sheet + cell ("p0101" is sheet 1, top left). Names: core',
            '/// pictograms.g.dart.',
            'const Map<String, IconData> hfPictos = {',
            *[f"  '{n}': IconData(0x{FIRST + i:X}, fontFamily: 'HfPictos')," for i, n in enumerate(names)],
            '};',
            '',
        ]
        return buf.getvalue(), '\n'.join(lines)
    lines = [
        '// GENERATED by tool/build_icons.py from design/icons. Do not edit.',
        "import 'package:flutter/widgets.dart';",
        '',
        '/// Clothes and pets drawn to match Material icons (Material has none).',
        'abstract final class HfIcons {',
    ]
    for i, n in enumerate(names):
        lines.append(f"  static const IconData {n} = IconData(0x{FIRST + i:X}, fontFamily: 'HfIcons');")
    lines += ['}', '']
    return buf.getvalue(), '\n'.join(lines)


PICTO_SRC = os.path.join(ROOT, '..', 'design', 'icons', 'sheets')
PICTO_FONT = os.path.join(ROOT, 'assets', 'fonts', 'HfPictos.ttf')
PICTO_DART = os.path.join(ROOT, 'lib', 'widgets', 'hf_pictos.g.dart')


def main():
    for src, family, font_path, dart_path in ((SRC, 'HfIcons', FONT, DART), (PICTO_SRC, 'HfPictos', PICTO_FONT, PICTO_DART)):
        font, dart = build(src, family)
        if '--check' in sys.argv:
            ok = os.path.exists(font_path) and os.path.exists(dart_path) and open(dart_path).read() == dart and open(font_path, 'rb').read() == font
            if not ok:
                print(f'{family} is out of date. Run: python3 tool/build_icons.py')
                sys.exit(1)
            print(f'{family} is up to date.')
            continue
        open(font_path, 'wb').write(font)
        open(dart_path, 'w').write(dart)
        print(f'Wrote {family}: {dart.count("IconData(")} icons, {len(font)} bytes, sha1 {hashlib.sha1(font).hexdigest()[:8]}')


if __name__ == '__main__':
    main()
