"""Reads the filled alias sheets (docs/asset-brief/aliases/filled-N.csv: the
order's CSVs with English names and Korean / English aliases filled in) and
writes core's pictogram_aliases.g.dart. Checks that every key is there once
and that the given columns were not changed.

    python3 tool/import_aliases.py
"""
import csv, glob, os, re, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DIR = os.path.join(ROOT, '..', 'docs', 'asset-brief', 'aliases')
NAMES = os.path.join(ROOT, 'packages', 'core', 'lib', 'src', 'pictograms.g.dart')
OUT = os.path.join(ROOT, 'packages', 'core', 'lib', 'src', 'pictogram_aliases.g.dart')


def q(s):
    return "'" + s.replace('\\', '\\\\').replace("'", "\\'").replace('$', '\\$') + "'"


def main():
    names = dict(re.findall(r"'(p\d{4})': '([^']*)'", open(NAMES).read()))
    rows = {}
    problems = []
    for path in sorted(glob.glob(os.path.join(DIR, 'filled-*.csv'))):
        for r in csv.DictReader(open(path, encoding='utf-8-sig')):
            k = (r.get('key') or '').strip()
            if k not in names:
                problems.append(f'{os.path.basename(path)}: unknown key {k!r}')
                continue
            if k in rows:
                problems.append(f'{k}: twice')
            if (r.get('ko_name') or '').strip() != names[k]:
                problems.append(f'{k}: ko_name changed to {r.get("ko_name")!r}')
            rows[k] = r
    missing = sorted(set(names) - set(rows))
    if missing:
        problems.append(f'missing {len(missing)}: {missing[:10]}')
    taken = {n.replace(' ', '') for n in names.values()}
    out = ['// GENERATED by tool/import_aliases.py from docs/asset-brief/aliases. Do not edit.', '',
           '/// English name of each ordered pictogram.', 'const Map<String, String> pictogramEn = {']
    for k in sorted(rows):
        out.append(f"  '{k}': {q((rows[k].get('en_name') or '').strip().lower())},")
    out += ['};', '', '/// Other names people use for each pictogram, Korean and English: a',
            "/// name that is another pictogram's own name is left out.", 'const Map<String, List<String>> pictogramAliases = {']
    dropped = 0
    for k in sorted(rows):
        r = rows[k]
        seen, words = set(), []
        for w in (r.get('ko_aliases') or '').split('|') + (r.get('en_aliases') or '').split('|'):
            w = w.strip()
            key = w.replace(' ', '').lower()
            if not w or key in seen or key == names[k].replace(' ', ''):
                continue
            if key in taken:
                dropped += 1
                continue
            seen.add(key)
            words.append(w if re.search(r'[가-힣]', w) else w.lower())
        out.append(f"  '{k}': [{', '.join(q(w) for w in words)}],")
    out += ['};', '']
    open(OUT, 'w').write('\n'.join(out))
    checks = [r for r in rows.values() if (r.get('picture_check') or '').strip() not in ('', 'ok')]
    print(f'{len(rows)} pictograms, {sum(1 for l in out if l.startswith("  ") and "[" in l)} alias lists, {dropped} aliases dropped (another icon\'s name), {len(checks)} picture notes')
    for r in checks:
        print('  picture:', r['key'], r['ko_name'], '->', r['picture_check'])
    if problems:
        print('\n'.join(problems))
        sys.exit(1)


if __name__ == '__main__':
    main()
